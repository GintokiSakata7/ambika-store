export function CategoryIconRenderer({ categoryId, size = 16, className = "" }) {
  switch (categoryId) {
    case "phenyl":
      return <IconDroplet size={size} className={className} />;
    case "acids":
      return <IconFlask size={size} className={className} />;
    case "naphthalene":
      return <IconShield size={size} className={className} />;
    case "powders":
      return <IconSparkles size={size} className={className} />;
    case "brooms":
      return <IconBrush size={size} className={className} />;
    case "accessories":
      return <IconLayers size={size} className={className} />;
    case "all":
      return <IconGrid size={size} className={className} />;
    default:
      return <IconPackage size={size} className={className} />;
  }
}

